const { chromium } = require('../node_modules/playwright')

;(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe' })
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
  const errors = []
  page.on('pageerror', (error) => errors.push(error.message))
  page.on('requestfailed', (request) => { if (request.url().startsWith('http://localhost:')) errors.push(`${request.url()}: ${request.failure()?.errorText}`) })
  await page.goto(process.env.SMOKE_URL || 'http://localhost:3000/', { waitUntil: 'networkidle' })
  await page.getByRole('heading', { name: 'Templates' }).waitFor()
  await page.getByRole('button', { name: /Career & purpose/ }).click()
  await page.getByRole('heading', { name: 'Photos' }).waitFor()
  await page.locator('.gratitude-style-panel').waitFor()
  await page.getByRole('button', { name: 'Rose' }).click()
  await page.locator('.tl-image').first().click()
  await page.getByRole('heading', { name: 'Arrange' }).waitFor()
  await page.getByRole('slider', { name: 'Opacity' }).fill('75')
  await page.getByRole('button', { name: 'Elements' }).click()
  await page.getByRole('button', { name: /Rose pin/ }).click()
  await page.getByRole('button', { name: /Reflection note/ }).click()
  await page.locator('.tl-image').nth(4).waitFor()
  await page.screenshot({ path: 'docs/gratitude-smoke.png', fullPage: true })
  await page.screenshot({ path: 'docs/gratitude-smoke.png', fullPage: true })
  console.log(JSON.stringify({ title: await page.title(), errors, images: await page.locator('.tl-image').count() }))
  await page.setViewportSize({ width: 390, height: 844 })
  await page.reload({ waitUntil: 'networkidle' })
  await page.getByRole('button', { name: 'Photos' }).click()
  await page.getByRole('button', { name: 'Close library' }).click()
  await page.screenshot({ path: 'docs/gratitude-mobile-smoke.png', fullPage: true })
  await browser.close()
  if (errors.length) process.exitCode = 1
})().catch((error) => { console.error(error); process.exitCode = 1 })
